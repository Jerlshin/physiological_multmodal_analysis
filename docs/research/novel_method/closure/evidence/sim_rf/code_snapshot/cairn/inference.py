"""CV engine, the NH1 tests T1 and T2, and the item-level metrics (plan §10, §20.1; spec §1.5, §2.2).

Units of inference
------------------
Item responses are **not** independent units. Responses are crossed by learner (all items and
videos of a learner), item (all learners answering it), video, and anchor moment (items that share
an evidence span share the moment regressor). Every procedure here respects that:

* outer CV folds are learner-grouped and experiment-stratified (all rows of a learner in one fold);
* T1 permutes **whole learners' moment-term blocks** among learners with the same tested-video
  pattern (Freedman-Lane on the moment block; person path and item terms stay in place), as G01-R
  permuted person blocks;
* T2 permutes **distinct anchor moments within each video**, one permutation for all learners, so
  its reference distribution is generated by ~19 (E4) to 59 (development) moments, not by item rows;
* the circular-shift null moves every anchor of a video by one common shift (>= 30 s, wrap-around);
* metrics are person-balanced (item -> learner -> mean over learners).

Statistic
---------
For a fitted model F against base B (IRT-M2): Delta = mean over learners of the learner's mean
held-out log-loss difference (B - F), averaged over the R repetitions. T1 and T2 both use the
observed Delta of CAIRN; T1's null refits CAIRN on learner-permuted moment blocks, T2's null on
relocated anchors. One-sided p = (1 + #{null >= observed}) / (1 + B).

Hyperparameters are fixed constants inside a test (no inner tuning inside the permutation loop;
variance components from the base model of each fold), so observed and permuted fits follow the
identical procedure (S1-D04).
"""
from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np
import pandas as pd

from . import features as F
from .design import Incidence
from .model import Fitter, Params, log_loss, predict_marginal

R_REPS = 3
K_FOLDS = 5
CIRC_MIN_S = 30
G_PEN = 1e-4          # video (x experiment) intercepts
R_F = 10.0            # person-path ridge (standardized columns)
R_M_MULTI = 100.0     # moment ridge, multi-channel CAIRN-linear (prior SD ~0.1 per channel)
R_M_ONE = 1.0         # moment ridge, single regressor


# ----------------------------------------------------------------------------- folds
def stratified_group_folds(persons: np.ndarray, strata: np.ndarray, k: int, seed: int) -> dict:
    """Deterministic learner -> fold map, balanced within each stratum (experiment)."""
    rng = np.random.default_rng(seed)
    out = {}
    offset = 0
    for s in sorted(set(strata)):
        ps = np.array(sorted(set(persons[strata == s])))
        rng.shuffle(ps)
        for i, p in enumerate(ps):
            out[p] = (i + offset) % k
        offset += len(ps)
    return out


# ----------------------------------------------------------------------------- structures
@dataclass(frozen=True)
class Variant:
    name: str
    channels: tuple = ()            # indices into features.PRIMARY for the moment block ('' = base)
    person_anch: bool = False       # e_anch (same channels) in the person path
    person_whole: bool = False      # e_bar (all channels) in the person path (IRT-whole)
    direction: tuple | None = None  # frozen channel weights -> one moment regressor (and one e_anch column)
    detrend: bool = False           # channels detrended within each recording before pooling (S1-D06)
    trend: int = 1                  # polynomial degree of that detrend (closure decision C-D03); 1 = Stage-1 form
    aniso: tuple | None = None      # (w0, r_par, r_perp): ridge r_par along unit direction w0, r_perp on its complement
    nuisance: tuple = ()            # moment channels always at the true anchors, never permuted (NH4 conditional test)

    @property
    def has_moment(self) -> bool:
        return bool(self.channels) or self.direction is not None

    @property
    def degree(self) -> int:
        """Pooler / moment-block key: 0 = raw channels, d >= 1 = degree-d within-recording detrend."""
        return self.trend if self.detrend else 0

    def r_m(self) -> float:
        return R_M_ONE if (self.direction is not None or len(self.channels) == 1) else R_M_MULTI

    def r_m_vec(self, n_cols: int) -> np.ndarray:
        if self.aniso is not None:
            _, r_par, r_perp = self.aniso
            return np.r_[np.full(len(self.nuisance), R_M_ONE), r_par, np.full(n_cols - len(self.nuisance) - 1, r_perp)]
        if self.nuisance:
            return np.r_[np.full(len(self.nuisance), R_M_ONE),
                         np.full(n_cols - len(self.nuisance), R_M_ONE if len(self.channels) == 1 or self.direction is not None
                                 else R_M_MULTI)]
        return np.full(n_cols, self.r_m())


BASE = Variant("IRT-M2")
WHOLE = Variant("IRT-whole", person_whole=True)
CL6 = Variant("CAIRN-linear", channels=tuple(range(len(F.PRIMARY))), person_anch=True)
CLV = Variant("CAIRN-validity", channels=(F.PRIMARY.index("loss_long"),), person_anch=True)
CLG = Variant("CAIRN-gaze", channels=tuple(F.PRIMARY.index(c) for c in F.GAZE), person_anch=True)
CL6_DT = Variant("CAIRN-linear-dt", channels=tuple(range(len(F.PRIMARY))), person_anch=True, detrend=True)
CLV_DT = Variant("CAIRN-validity-dt", channels=(F.PRIMARY.index("loss_long"),), person_anch=True, detrend=True)
CLG_DT = Variant("CAIRN-gaze-dt", channels=tuple(F.PRIMARY.index(c) for c in F.GAZE), person_anch=True, detrend=True)


def direction_variant(w: np.ndarray, name: str = "CAIRN-linear-dir", detrend: bool = False, trend: int = 1) -> Variant:
    w = np.asarray(w, float)
    w = w / (np.linalg.norm(w) or 1.0)
    return Variant(name, channels=tuple(range(len(F.PRIMARY))), person_anch=True, direction=tuple(np.round(w, 12)),
                   detrend=detrend, trend=trend)


# Unit-weighted engagement composite (closure decision C-D05): equal weights on the six standardized, sign-aligned
# moment regressors. The signs are the outcome-free Stage-0 construct signs (distracted vs attentive viewing,
# features.ENGAGED_SIGN); no outcome of any cohort enters the weights.
UNIT_W = np.array([F.ENGAGED_SIGN[c] for c in F.PRIMARY]) / np.sqrt(len(F.PRIMARY))


def unit_variant(trend: int, name: str | None = None) -> Variant:
    """P0: the 1-df unit-weighted composite (moment term and its anchored person-path summary)."""
    return direction_variant(UNIT_W, name=name or f"CAIRN-u-dt{trend}", detrend=True, trend=trend)


def six_variant(trend: int, name: str | None = None) -> Variant:
    """P6: the Stage-1 six-channel isotropic-ridge block (CAIRN-linear-dt when trend = 1)."""
    if trend == 1 and name is None:
        return CL6_DT
    return Variant(name or f"CAIRN-linear-dt{trend}", channels=tuple(range(len(F.PRIMARY))), person_anch=True,
                   detrend=True, trend=trend)


def aniso_variant(trend: int, r_par: float = R_M_ONE, r_perp: float = R_M_MULTI, name: str | None = None) -> Variant:
    """PT: six channels with an anisotropic ridge centred on the unit-weighted direction: ridge ``r_par`` on the
    (re-standardized) composite, ``r_perp`` on the 5-dimensional orthogonal complement (C-D05)."""
    return Variant(name or f"CAIRN-t-dt{trend}", channels=tuple(range(len(F.PRIMARY))), person_anch=True, detrend=True,
                   trend=trend, aniso=(tuple(np.round(UNIT_W, 12)), float(r_par), float(r_perp)))


def gaze_given_validity_variant(trend: int, name: str | None = None) -> Variant:
    """NH4 attribution (S1-D16 / C-D07): the gaze block tested conditional on the in-window validity term, which
    stays at the true anchors in every permutation."""
    return Variant(name or f"CAIRN-gaze|val-dt{trend}", channels=tuple(F.PRIMARY.index(c) for c in F.GAZE),
                   person_anch=True, detrend=True, trend=trend, nuisance=(F.PRIMARY.index("loss_long"),))


def complement_basis(w0: np.ndarray) -> np.ndarray:
    """Orthonormal basis (D x (D-1)) of the complement of unit vector w0 (deterministic: QR of [w0 | I])."""
    D = len(w0)
    q, _ = np.linalg.qr(np.column_stack([w0, np.eye(D)]))
    q = q[:, :D]
    if q[:, 0] @ w0 < 0:
        q = -q
    return q[:, 1:]


@dataclass
class Split:
    rep: int
    fold: int
    train_persons: frozenset
    train: np.ndarray             # rows
    test: np.ndarray
    anch_train: np.ndarray        # anchorable rows that are training rows
    fitter: Fitter
    pooler: F.Pooler
    mb: F.MomentBlock             # true anchors
    q: np.ndarray                 # cells, standardized on training cells
    cell_train: np.ndarray        # cells of training learners
    sc: F.SplitChannels | None = None   # kept for the canonical split only
    pooler_dt: F.Pooler | None = None   # detrended channels (S1-D06)
    mb_dt: F.MomentBlock | None = None
    extra: dict = field(default_factory=dict)   # degree (>= 2) -> (Pooler, MomentBlock): polynomial detrend (C-D03)

    def pl(self, var: "Variant") -> F.Pooler:
        d = var.degree
        return self.pooler if d == 0 else self.pooler_dt if d == 1 else self.extra[d][0]

    def block(self, var: "Variant") -> F.MomentBlock:
        d = var.degree
        return self.mb if d == 0 else self.mb_dt if d == 1 else self.extra[d][1]

    @property
    def any_block(self) -> F.MomentBlock:
        """A moment block for the whole-recording means e_bar (identical for every degree: detrending keeps means)."""
        return next(b for b in (self.mb, self.mb_dt, *(v[1] for v in self.extra.values())) if b is not None)


@dataclass
class SetStructure:
    inc: Incidence
    n: int
    item: np.ndarray
    person: np.ndarray
    cell: np.ndarray
    group: np.ndarray
    G: np.ndarray
    anch: np.ndarray              # bool rows
    anch_index: np.ndarray
    anch_cell: np.ndarray
    anch_item: np.ndarray
    anch_video: np.ndarray
    anch_moment: np.ndarray
    persons: np.ndarray           # person id per person index
    person_exp: np.ndarray
    patterns: dict                # (experiment, videos) -> person indices
    anch_key: dict                # (person_idx, video, item) -> anchorable position
    anch_pvj: list                # per anchorable position: (person_idx, video, item)
    q_raw: np.ndarray             # cell invalid fraction
    splits: list = field(default_factory=list)
    canonical: Split | None = None
    moment_centre: dict = field(default_factory=dict)   # video -> array of moment centres
    n_moments: dict = field(default_factory=dict)


def build_structure(inc: Incidence, reps: int = R_REPS, k: int = K_FOLDS, cv_seed: int = 0, regime: str = "A",
                    with_splits: bool = True, degrees: tuple = (0, 1)) -> SetStructure:
    """``degrees``: the moment blocks precomputed per split (0 = raw channels; d >= 1 = degree-d detrend)."""
    rows, cells = inc.rows, inc.cells
    persons = np.array(sorted(cells.person.unique()))
    pidx = {p: i for i, p in enumerate(persons)}
    cidx = {u: i for i, u in enumerate(cells.uid)}
    items = sorted(rows.item_key.unique())
    kidx = {it: i for i, it in enumerate(items)}
    groups = sorted(set(zip(rows.experiment, rows.video)))
    gidx = {g: i for i, g in enumerate(groups)}
    item = rows.item_key.map(kidx).to_numpy()
    person = rows.person.map(pidx).to_numpy()
    cell = rows.uid.map(cidx).to_numpy()
    group = np.array([gidx[g] for g in zip(rows.experiment, rows.video)])
    anch = rows.anchorable.to_numpy()
    anch_index = np.flatnonzero(anch)
    ra = rows[anch]
    person_exp = cells.groupby("person").experiment.first().reindex(persons).to_numpy()
    pat = {}
    for p, g in cells.groupby("person"):
        pat.setdefault((int(g.experiment.iloc[0]), tuple(sorted(g.video))), []).append(pidx[p])
    anch_pvj = [(pidx[p], v, int(j)) for p, v, j in zip(ra.person, ra.video, ra.item)]
    S = SetStructure(inc, len(rows), item, person, cell, group, np.eye(len(groups))[group], anch, anch_index,
                     ra.uid.map(cidx).to_numpy(), ra.item_key.map(kidx).to_numpy(), ra.video.to_numpy(),
                     ra.moment.to_numpy(), persons, person_exp, pat, {t: i for i, t in enumerate(anch_pvj)}, anch_pvj,
                     1.0 - cells.valid_fraction.to_numpy(float))
    cen = F.moment_centres(inc)
    for v in inc.n_s:
        ms = sorted(m for (vv, m) in cen if vv == v)
        S.moment_centre[v] = np.array([cen[(v, m)] for m in ms])
        S.n_moments[v] = len(ms)
    # the canonical split always carries the raw block: the simulation's truth is built from raw channels
    S.canonical = make_split(S, -1, -1, frozenset(persons), regime, tuple(sorted(set(degrees) | {0})))
    if with_splits:
        strata = person_exp
        for r in range(reps):
            fmap = stratified_group_folds(persons, strata, k, seed=cv_seed + r)
            for f in range(k):
                train_p = frozenset(p for p in persons if fmap[p] != f)
                S.splits.append(make_split(S, r, f, train_p, regime, degrees))
    return S


def make_split(S: SetStructure, rep: int, fold: int, train_persons: frozenset, regime: str = "A",
               degrees: tuple = (0, 1)) -> Split:
    inc = S.inc
    sc = F.compute_split(inc, train_persons, regime=regime)
    pooler = mb = pooler_dt = mb_dt = None
    if 0 in degrees:
        pooler = F.Pooler(inc, sc)
        mb = F.moment_block(inc, pooler)
    if 1 in degrees:
        pooler_dt = F.Pooler(inc, sc, detrend=True)
        mb_dt = F.moment_block(inc, pooler_dt)
    extra = {}
    for d in sorted(set(degrees) - {0, 1}):
        pl_d = F.Pooler(inc, sc, detrend=True, degree=d)
        extra[d] = (pl_d, F.moment_block(inc, pl_d))
    train = np.isin(S.persons[S.person], list(train_persons))
    if rep < 0:                                   # canonical: everything is "training"
        train = np.ones(S.n, bool)
    test = ~train
    tp = sorted(set(S.person[train]))
    remap = np.full(len(S.persons), -1)
    remap[tp] = np.arange(len(tp))
    fitter = Fitter(S.item[train], remap[S.person[train]], int(S.item.max()) + 1, len(tp))
    cell_train = np.zeros(len(inc.cells), bool)
    cell_train[np.unique(S.cell[train])] = True
    q = _std_cells(S.q_raw[:, None], cell_train)[:, 0]
    return Split(rep, fold, train_persons, train, test, train[S.anch_index], fitter, pooler, mb, q, cell_train,
                 sc if rep < 0 else None, pooler_dt, mb_dt, extra)


def _std_cells(X: np.ndarray, cell_train: np.ndarray) -> np.ndarray:
    mu = np.nanmean(X[cell_train], 0)
    sd = np.nanstd(X[cell_train], 0)
    sd = np.where(sd > 0, sd, 1.0)
    return np.nan_to_num((X - mu) / sd)


# ----------------------------------------------------------------------------- designs
def _unit_sd(x: np.ndarray, rows: np.ndarray) -> np.ndarray:
    sd = x[rows].std()
    return x / (sd if sd > 0 else 1.0)


def moment_columns(S: SetStructure, sp: Split, var: Variant, m: np.ndarray) -> np.ndarray:
    """Moment regressors for all rows (zero on non-anchorable rows) from anchorable moment terms m.

    ``var.nuisance`` channels always come from the split's true-anchor block (never permuted) and are placed
    first; ``var.aniso`` rotates the six standardized regressors onto (w0, complement of w0), with the w0 column
    re-standardized, so that the ridge vector of :meth:`Variant.r_m_vec` acts along w0 and across its complement."""
    x = F.moment_regressors(m[:, list(var.channels)], S.anch_cell, S.anch_item, sp.anch_train)
    if var.direction is not None:
        x = _unit_sd(x @ np.asarray(var.direction)[:, None], sp.anch_train)
    elif var.aniso is not None:
        w0 = np.asarray(var.aniso[0])
        x = np.column_stack([_unit_sd(x @ w0, sp.anch_train), x @ complement_basis(w0)])
    if var.nuisance:
        xn = F.moment_regressors(sp.block(var).m[:, list(var.nuisance)], S.anch_cell, S.anch_item, sp.anch_train)
        x = np.column_stack([xn, x])
    out = np.zeros((S.n, x.shape[1]))
    out[S.anch_index] = x
    return out


def person_columns(S: SetStructure, sp: Split, var: Variant) -> np.ndarray:
    cols = [sp.q[:, None]]
    if var.person_anch:
        e = sp.block(var).eanch[:, list(var.nuisance) + list(var.channels)]
        if var.direction is not None:
            e = np.nan_to_num(_std_cells(e, sp.cell_train)) @ np.asarray(var.direction)[:, None]
        cols.append(_std_cells(e, sp.cell_train))
    if var.person_whole:
        cols.append(_std_cells(sp.any_block.ebar, sp.cell_train))
    return np.hstack(cols)[S.cell]


def design(S: SetStructure, sp: Split, var: Variant, m: np.ndarray | None = None, fixed: np.ndarray | None = None):
    """Dense design (rows x d) and its ridge vector. ``fixed`` = precomputed [G | person path]."""
    fixed = np.hstack([S.G, person_columns(S, sp, var)]) if fixed is None else fixed
    pen = [np.full(S.G.shape[1], G_PEN), np.full(fixed.shape[1] - S.G.shape[1], R_F)]
    if var.has_moment:
        mc = moment_columns(S, sp, var, sp.block(var).m if m is None else m)
        pen.append(var.r_m_vec(mc.shape[1]))
        return np.hstack([fixed, mc]), np.concatenate(pen)
    return fixed, np.concatenate(pen)


# ----------------------------------------------------------------------------- fitting
@dataclass
class FoldFit:
    base: Params
    p_base: np.ndarray            # test-row predictions of the base model
    fixed: dict = field(default_factory=dict)   # variant name -> fixed design columns


def fit_base(S: SetStructure, sp: Split, y: np.ndarray) -> FoldFit:
    D, pen = design(S, sp, BASE)
    prm = sp.fitter.fit_em(D[sp.train], y[sp.train], pen)
    return FoldFit(prm, predict_marginal(prm, S.item[sp.test], D[sp.test]))


def fit_variant(S: SetStructure, sp: Split, ff: FoldFit, var: Variant, y: np.ndarray, m: np.ndarray | None = None,
                init: Params | None = None):
    if var.name not in ff.fixed:
        ff.fixed[var.name] = np.hstack([S.G, person_columns(S, sp, var)])
    D, pen = design(S, sp, var, m, ff.fixed[var.name])
    prm = sp.fitter.newton(D[sp.train], y[sp.train], pen, ff.base.tau2, ff.base.sb2, init=init or ff.base)
    return prm, predict_marginal(prm, S.item[sp.test], D[sp.test])


# ----------------------------------------------------------------------------- metrics
def person_balanced(v: np.ndarray, person: np.ndarray) -> float:
    s = np.bincount(person, v)
    n = np.bincount(person)
    ok = n > 0
    return float(np.mean(s[ok] / n[ok]))


def cell_auc(y: np.ndarray, p: np.ndarray, cell: np.ndarray) -> np.ndarray:
    """AUC within each cell (NaN when the cell has only correct or only incorrect items)."""
    out = np.full(int(cell.max()) + 1, np.nan)
    order = np.argsort(cell, kind="stable")
    bounds = np.flatnonzero(np.r_[True, np.diff(cell[order]) != 0, True])
    for a, b in zip(bounds[:-1], bounds[1:]):
        idx = order[a:b]
        yy, pp = y[idx], p[idx]
        npos = yy.sum()
        nneg = len(yy) - npos
        if npos == 0 or nneg == 0:
            continue
        ranks = _rank(pp)
        out[cell[idx[0]]] = (ranks[yy == 1].sum() - npos * (npos + 1) / 2) / (npos * nneg)
    return out


def _rank(x):
    from scipy.stats import rankdata
    return rankdata(x)


def delta_auc_wp(y, p_full, p_base, cell, cell_person) -> float:
    a1, a0 = cell_auc(y, p_full, cell), cell_auc(y, p_base, cell)
    ok = np.isfinite(a1) & np.isfinite(a0)
    d = (a1 - a0)[ok]
    per = pd.Series(d).groupby(cell_person[ok]).mean()
    return float(per.mean()) if len(per) else np.nan


def corrected_upper(fold_d: np.ndarray, k: int, z: float) -> float:
    """Nadeau-Bengio corrected resampled-t upper bound (as G01-R's futility bound)."""
    J = len(fold_d)
    v = np.var(fold_d, ddof=1) * (1 / J + 1 / (k - 1))
    return float(np.mean(fold_d) + z * np.sqrt(v))


# ----------------------------------------------------------------------------- CV evaluation
@dataclass
class CVResult:
    ll_base: np.ndarray           # per row, mean over repetitions
    ll_full: dict                 # variant -> per-row mean loss
    p_base: np.ndarray            # per row, mean prediction over repetitions
    p_full: dict
    fold_d: dict                  # variant -> per-fold person-balanced loss difference
    fits: list                    # FoldFit per split
    params: dict                  # variant -> list of Params per split


def cv_evaluate(S: SetStructure, y: np.ndarray, variants: list) -> CVResult:
    n = S.n
    llb = np.zeros(n)
    pb = np.zeros(n)
    cnt = np.zeros(n)
    llf = {v.name: np.zeros(n) for v in variants}
    pf = {v.name: np.zeros(n) for v in variants}
    fold_d = {v.name: [] for v in variants}
    fits, params = [], {v.name: [] for v in variants}
    for sp in S.splits:
        ff = fit_base(S, sp, y)
        fits.append(ff)
        te = sp.test
        lb = log_loss(y[te], ff.p_base)
        llb[te] += lb
        pb[te] += ff.p_base
        cnt[te] += 1
        for v in variants:
            prm, p = fit_variant(S, sp, ff, v, y)
            params[v.name].append(prm)
            lf = log_loss(y[te], p)
            llf[v.name][te] += lf
            pf[v.name][te] += p
            fold_d[v.name].append(person_balanced(lb - lf, _reindex(S.person[te])))
    cnt = np.maximum(cnt, 1)
    return CVResult(llb / cnt, {k: v / cnt for k, v in llf.items()}, pb / cnt, {k: v / cnt for k, v in pf.items()},
                    {k: np.array(v) for k, v in fold_d.items()}, fits, params)


def _reindex(a: np.ndarray) -> np.ndarray:
    _, inv = np.unique(a, return_inverse=True)
    return inv


def summarize(S: SetStructure, y: np.ndarray, cv: CVResult, name: str) -> dict:
    lb = person_balanced(cv.ll_base, S.person)
    lf = person_balanced(cv.ll_full[name], S.person)
    cell_person = S.inc.cells.person.map({p: i for i, p in enumerate(S.persons)}).to_numpy()
    fd = cv.fold_d[name] / lb
    return dict(ll_base=lb, ll_full=lf, delta=lb - lf, s_item=1 - lf / lb,
                d_auc_wp=delta_auc_wp(y, cv.p_full[name], cv.p_base, S.cell, cell_person),
                s_item_upper_z1645=corrected_upper(fd, K_FOLDS, 1.645), s_item_upper_z3=corrected_upper(fd, K_FOLDS, 3.0))


# ----------------------------------------------------------------------------- permutation nulls
def learner_block_permutation(S: SetStructure, rng: np.random.Generator) -> np.ndarray:
    """Anchorable-row index map: target row receives the moment terms of row perm[target]. Whole
    learners are exchanged among learners of the same experiment and tested-video pattern."""
    src_person = np.arange(len(S.persons))
    for key in sorted(S.patterns):
        members = np.array(S.patterns[key])
        if len(members) > 1:
            src_person[members] = rng.permutation(members)
    return np.array([S.anch_key[(src_person[p], v, j)] for (p, v, j) in S.anch_pvj])


def moment_permutation(S: SetStructure, rng: np.random.Generator) -> dict:
    return {v: rng.permutation(S.n_moments[v]) for v in S.n_moments}


def relocation_shift(S: SetStructure, perm: dict) -> np.ndarray:
    """Per anchorable row: the shift that moves its moment to perm[video][moment]."""
    out = np.zeros(len(S.anch_index))
    for v, pm in perm.items():
        sel = S.anch_video == v
        cen = S.moment_centre[v]
        mm = S.anch_moment[sel]
        out[sel] = cen[pm[mm]] - cen[mm]
    return out


def circular_shift(S: SetStructure, rng: np.random.Generator) -> np.ndarray:
    out = np.zeros(len(S.anch_index), int)
    for v, n_s in S.inc.n_s.items():
        out[S.anch_video == v] = rng.integers(CIRC_MIN_S, n_s - CIRC_MIN_S + 1)
    return out


def relocated_terms(S: SetStructure, sp: Split, delta: np.ndarray, var: Variant = CL6) -> np.ndarray:
    pl = sp.pl(var)
    s, e = pl.start + delta, pl.end + delta
    over = np.maximum(e - pl.n_s, 0)
    under = np.maximum(-s, 0)
    z = pl.means(s - over + under, e - over + under)
    return z - sp.block(var).ebar[pl.cell]


def shifted_terms(S: SetStructure, sp: Split, shift: np.ndarray, var: Variant = CL6) -> np.ndarray:
    pl = sp.pl(var)
    z = pl.means(shift=shift)
    return z - sp.block(var).ebar[pl.cell]


def null_statistic(S: SetStructure, y: np.ndarray, cv: CVResult, var: Variant, m_of_split) -> float:
    """Delta of ``var`` refitted with moment terms m_of_split(split) (same folds, same base fits)."""
    n = S.n
    llf = np.zeros(n)
    cnt = np.zeros(n)
    for sp, ff in zip(S.splits, cv.fits):
        _, p = fit_variant(S, sp, ff, var, y, m=m_of_split(sp))      # same start (base fit) as the observed fit
        llf[sp.test] += log_loss(y[sp.test], p)
        cnt[sp.test] += 1
    llf /= np.maximum(cnt, 1)
    return person_balanced(cv.ll_base, S.person) - person_balanced(llf, S.person)


# ----------------------------------------------------------------------------- full-data (LR) statistics
@dataclass
class FullBase:
    base: Params
    ll_base: float
    fixed: dict = field(default_factory=dict)


def _cond_loglik(S: SetStructure, sp: Split, prm: Params, D: np.ndarray, y: np.ndarray) -> float:
    from scipy.special import log_expit
    eta = prm.a[S.item] + prm.u[sp.fitter.p] + D @ prm.b
    return float(np.sum(y * log_expit(eta) + (1 - y) * log_expit(-eta)))


def full_base(S: SetStructure, y: np.ndarray) -> FullBase:
    """Base model (IRT-M2) on all rows of the set, variance components by Laplace-EM."""
    can = S.canonical
    D, pen = design(S, can, BASE)
    prm = can.fitter.fit_em(D, y, pen)
    return FullBase(prm, _cond_loglik(S, can, prm, D, y))


def full_gain(S: SetStructure, y: np.ndarray, fb: FullBase, var: Variant, m: np.ndarray | None = None) -> float:
    """Likelihood-ratio statistic: conditional log-likelihood gain of ``var`` over the base on all rows (same
    variance components). Moment terms come from the canonical (leave-one-learner-out reference) split."""
    can = S.canonical
    if var.name not in fb.fixed:
        fb.fixed[var.name] = np.hstack([S.G, person_columns(S, can, var)])
    D, pen = design(S, can, var, m, fb.fixed[var.name])
    prm = can.fitter.newton(D, y, pen, fb.base.tau2, fb.base.sb2, init=fb.base)
    return _cond_loglik(S, can, prm, D, y) - fb.ll_base


def perm_p(obs: float, null: np.ndarray) -> float:
    return float((1 + np.sum(np.asarray(null) >= obs - 1e-12)) / (1 + len(null)))


def run_tests(S: SetStructure, y: np.ndarray, cv: CVResult, var: Variant, B: int, rng: np.random.Generator,
              tests=("T1", "T2", "T2c")) -> dict:
    obs = person_balanced(cv.ll_base, S.person) - person_balanced(cv.ll_full[var.name], S.person)
    out = {}
    if "T1" in tests:
        null = [null_statistic(S, y, cv, var, lambda sp, pr=learner_block_permutation(S, rng): sp.block(var).m[pr])
                for _ in range(B)]
        out["T1"] = perm_p(obs, null)
    if "T2" in tests:
        null = [null_statistic(S, y, cv, var, lambda sp, d=relocation_shift(S, moment_permutation(S, rng)):
                               relocated_terms(S, sp, d, var)) for _ in range(B)]
        out["T2"] = perm_p(obs, null)
    if "T2c" in tests:
        null = [null_statistic(S, y, cv, var, lambda sp, sh=circular_shift(S, rng): shifted_terms(S, sp, sh, var))
                for _ in range(B)]
        out["T2c"] = perm_p(obs, null)
    lr = [t for t in tests if t.endswith("lr")]
    if lr:
        # same nulls with the full-data likelihood-ratio statistic (candidate redesign, S1-D09)
        can = S.canonical
        fb = full_base(S, y)
        obs_lr = full_gain(S, y, fb, var)
        if "T1lr" in lr:
            out["T1lr"] = perm_p(obs_lr, [full_gain(S, y, fb, var, can.block(var).m[learner_block_permutation(S, rng)])
                                          for _ in range(B)])
        if "T2lr" in lr:
            out["T2lr"] = perm_p(obs_lr, [full_gain(S, y, fb, var, relocated_terms(S, can, relocation_shift(S, moment_permutation(S, rng)), var))
                                          for _ in range(B)])
        if "T2clr" in lr:
            out["T2clr"] = perm_p(obs_lr, [full_gain(S, y, fb, var, shifted_terms(S, can, circular_shift(S, rng), var))
                                           for _ in range(B)])
        out["lr_stat"] = obs_lr
    return out


# ----------------------------------------------------------------------------- joint permutation tests (closure)
def minp_from_stats(stats: np.ndarray) -> float:
    """Exact single-step min-p combination of k statistics over one permutation set.

    ``stats`` is (B + 1) x k: row 0 the observed statistics, rows 1..B the same statistics under the same B
    permutation draws. Each statistic's p-value is computed for every row against all B + 1 rows; the observed
    minimum p is referred to the distribution of row minima (Westfall & Young 1993). Under exchangeability of the
    B + 1 rows the result is an exact level-alpha p-value for the combined (adaptive) test."""
    st = np.asarray(stats, float)
    n = st.shape[0]
    # p_ij = #{l : s_lj >= s_ij} / n  (with the same 1e-12 tolerance as perm_p)
    p = np.stack([(st[None, :, j] >= st[:, None, j] - 1e-12).sum(1) / n for j in range(st.shape[1])], 1)
    mins = p.min(1)
    return float(np.sum(mins <= mins[0] + 1e-15) / n)


def lr_tests_joint(S: SetStructure, y: np.ndarray, variants: list, B: int, rng: np.random.Generator,
                   tests=("T1lr", "T2lr", "T2clr"), combos: dict | None = None) -> dict:
    """Likelihood-ratio statistics of several variants under **one** set of permutation draws per null.

    Every draw (learner-block permutation, moment relocation or circular shift) is applied to every variant, so the
    variants' p-values are paired and any min-p combination in ``combos`` ({name: [variant names]}) is exact. Each
    variant's p-value equals what :func:`run_tests` would give for the same draws."""
    can = S.canonical
    fb = full_base(S, y)
    obs = np.array([full_gain(S, y, fb, v) for v in variants])
    out = {f"{v.name}|lr_stat": float(o) for v, o in zip(variants, obs)}
    names = [v.name for v in variants]
    for t in tests:
        rows = [obs]
        for _ in range(B):
            if t == "T1lr":
                pr = learner_block_permutation(S, rng)
                rows.append([full_gain(S, y, fb, v, can.block(v).m[pr]) for v in variants])
            elif t == "T2lr":
                d = relocation_shift(S, moment_permutation(S, rng))
                rows.append([full_gain(S, y, fb, v, relocated_terms(S, can, d, v)) for v in variants])
            elif t == "T2clr":
                sh = circular_shift(S, rng)
                rows.append([full_gain(S, y, fb, v, shifted_terms(S, can, sh, v)) for v in variants])
            else:
                raise ValueError(t)
        st = np.asarray(rows, float)
        for j, nm in enumerate(names):
            out[f"{nm}|p_{t}"] = perm_p(st[0, j], st[1:, j])
        for cname, members in (combos or {}).items():
            idx = [names.index(m) for m in members]
            out[f"{cname}|p_{t}"] = minp_from_stats(st[:, idx])
    return out


def lambda_hat(S: SetStructure, y: np.ndarray, var: Variant) -> dict:
    """Full-data estimate of a 1-df moment coefficient (last column) with its model-based SE (descriptive)."""
    can = S.canonical
    D0, pen0 = design(S, can, BASE)
    base = can.fitter.fit_em(D0, y, pen0)
    D, pen = design(S, can, var)
    prm, cov = can.fitter.newton(D, y, pen, base.tau2, base.sb2, init=base, want_cov=True)
    return dict(lam=float(prm.b[-1]), se=float(np.sqrt(cov[-1, -1])))


# ----------------------------------------------------------------------------- nested-CV interval (secondary)
def person_diffs(ll_base: np.ndarray, ll_full: np.ndarray, person: np.ndarray) -> np.ndarray:
    """Per-learner mean held-out log-loss difference (base - full)."""
    s = np.bincount(person, ll_base - ll_full)
    n = np.bincount(person)
    return (s[n > 0] / n[n > 0])


def nested_cv(S: SetStructure, y: np.ndarray, var: Variant, cv: CVResult | None = None, K: int = K_FOLDS,
              reps: int = 1, seed: int = 100, level: float = 0.90) -> dict:
    """Nested-CV interval for the person-balanced log-loss gain of ``var`` over IRT-M2 (Bates, Hastie &
    Tibshirani 2024), combined with the frozen G01-R implementation (``g01r.inference.nested_cv_interval``).
    Every inner and outer split recomputes its references and standardization on its own training learners."""
    from g01r.inference import nested_cv_interval as combine

    cv = cv_evaluate(S, y, [var]) if cv is None else cv
    pdiff = person_diffs(cv.ll_base, cv.ll_full[var.name], S.person)
    delta_cv = float(pdiff.mean())
    base_loss = person_balanced(cv.ll_base, S.person)
    persons = S.persons
    pieces = []
    for r in range(reps):
        fmap = stratified_group_folds(persons, S.person_exp, K, seed + r)
        f_row = np.array([fmap[p] for p in persons])[S.person]
        out = dict(a=[], b=[], e_in=[])
        for k in range(K):
            outer = f_row != k
            lb_in, lf_in = np.full(S.n, np.nan), np.full(S.n, np.nan)
            for j in range(K):
                if j == k:
                    continue
                train_p = frozenset(persons[np.unique(S.person[outer & (f_row != j)])])
                sp = make_split(S, r, 100 * k + j, train_p)
                ff = fit_base(S, sp, y)
                _, pf = fit_variant(S, sp, ff, var, y)
                rows = np.flatnonzero(sp.test)
                sel = f_row[rows] == j
                lb_in[rows[sel]] = log_loss(y[rows[sel]], ff.p_base[sel])
                lf_in[rows[sel]] = log_loss(y[rows[sel]], pf[sel])
            sp = make_split(S, r, 100 * k + 99, frozenset(persons[np.unique(S.person[outer])]))
            ff = fit_base(S, sp, y)
            _, pf = fit_variant(S, sp, ff, var, y)
            te = np.flatnonzero(sp.test)
            e_in = person_diffs(lb_in[outer], lf_in[outer], _reindex(S.person[outer]))
            e_out = person_diffs(log_loss(y[te], ff.p_base), log_loss(y[te], pf), _reindex(S.person[te]))
            out["a"].append((e_in.mean() - e_out.mean()) ** 2)
            out["b"].append(e_out.var(ddof=1) / len(e_out))
            out["e_in"].append(e_in)
        pieces.append(out)
    res = combine(pieces, delta_cv, pdiff, base_loss, K, level)
    res["s_item_lo"], res["s_item_hi"] = res.pop("lo_skill"), res.pop("hi_skill")
    res["s_item_centre"] = res.pop("centre_skill")
    return res
